def validate_inventory(document: dict[str, Any]) -> None:
    """Validate invariants used by tests and CI without reading raw payloads."""
    for item in document["claims"]:
        if item["status"] not in STATUSES:
            raise ValueError(f"invalid status: {item['claim_id']}")
        if item["confidence"] not in CONFIDENCES:
            raise ValueError(f"invalid confidence: {item['claim_id']}")
        if not item["source_location"]:
            raise ValueError(f"missing source location: {item['claim_id']}")
        if item["relationship"] is not None and item["relationship"] not in RELATIONSHIPS:
            raise ValueError(f"invalid relationship: {item['claim_id']}")
        if item["status"] == "SUPPORTED" and not item["raw_sources"]:
            raise ValueError(f"supported claim has no raw source: {item['claim_id']}")


def write_inventory(path: Path = OUTPUT) -> None:
    document = build_inventory()
    validate_inventory(document)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(document, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
        newline="\n",
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args(argv)
    write_inventory(args.output)
    return 0


